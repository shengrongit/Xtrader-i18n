function buildUiMap(zh, map) {
  const out = {}
  const missing = []
  for (const key of Object.keys(zh)) {
    if (shouldSkipKey(key, zh[key])) continue
    if (!(key in map)) {
      missing.push(key)
      continue
    }
    out[key] = map[key]
  }
  return { out, missing }
}

function main() {
  const zh = JSON.parse(fs.readFileSync(zhPath, 'utf8'))
  const { out: viOut, missing: viMissing } = buildUiMap(zh, VI)
  const { out: idOut, missing: idMissing } = buildUiMap(zh, ID)

  if (viMissing.length || idMissing.length) {
    console.error('Missing VI:', viMissing)
    console.error('Missing ID:', idMissing)
    process.exit(1)
  }

  fs.writeFileSync(viUiPath, `${JSON.stringify(viOut, null, 2)}\n`, 'utf8')
  fs.writeFileSync(idUiPath, `${JSON.stringify(idOut, null, 2)}\n`, 'utf8')
  console.log(`Generated ui-vi.json: ${Object.keys(viOut).length} keys`)
  console.log(`Generated ui-id.json: ${Object.keys(idOut).length} keys`)
}

main()
